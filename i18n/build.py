"""Build the Dutch and French landing pages from index.html.

index.html (English) is the only page you edit by hand. This script copies it to
nl/index.html and fr/index.html, swapping every English text for the one in
i18n/nl.json or i18n/fr.json. Run it from the repo root after every change:

    python3 i18n/build.py

It lists any English text that has no translation yet (the page then shows the
English text there). Add the missing lines to the JSON files and run it again.
"""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = 'https://kalyd.app'
LANGS = {'nl': 'nl_BE', 'fr': 'fr_BE'}
TEXT_ATTRS = ('alt', 'aria-label', 'placeholder', 'title', 'data-stop')
META_KEYS = ('description', 'og:title', 'og:description', 'og:image:alt', 'twitter:title', 'twitter:description')
URL_ATTRS = ('src', 'href', 'poster')
TOKEN = re.compile(r'(<!--.*?-->|<script\b.*?</script>|<style\b.*?</style>|<[^>]+>)', re.S | re.I)
ATTR = re.compile(r'(\s)([\w:-]+)="([^"]*)"')


def norm(s):
    return ' '.join(s.split())


def build(lang, locale, src):
    data = json.loads((ROOT / 'i18n' / f'{lang}.json').read_text(encoding='utf-8'))
    text, js, keep = data['text'], data.get('js', {}), set(data.get('keep', []))
    missing = []

    def tr(s):
        key = norm(s)
        if not key or not re.search('[A-Za-z]', key) or key in keep:
            return s
        if key not in text:
            missing.append(key)
            return s
        lead, trail = s[:len(s) - len(s.lstrip())], s[len(s.rstrip()):]
        return lead + text[key] + trail

    def fix_url(v):
        if not v or re.match(r'(https?:|/|#|mailto:|tel:|data:|javascript:)', v):
            return v
        return '/' + v

    def tag(t):
        meta = re.search(r'\b(?:name|property)="([^"]+)"', t) if t.lower().startswith('<meta') else None

        def attr(m):
            sp, k, v = m.groups()
            if k in TEXT_ATTRS or (k == 'content' and meta and meta.group(1) in META_KEYS):
                v = tr(v)
            elif k in URL_ATTRS:
                v = fix_url(v)
            return f'{sp}{k}="{v}"'
        return ATTR.sub(attr, t)

    def script(t):
        for en, loc in js.items():
            for q in ("'", '"', '`'):
                if q + en + q in t:
                    t = t.replace(q + en + q, q + loc.replace(q, '\\' + q) + q)
        return re.sub(r"(['\"])([\w-]+\.(?:mp4|webp|png|jpe?g|svg|html))\1", r'\1/\2\1', t)

    out = []
    for part in TOKEN.split(src):
        if not part:
            continue
        low = part[:7].lower()
        if low.startswith('<script'):
            out.append(script(part))
        elif low.startswith('<style') or part.startswith('<!--'):
            out.append(part)
        elif part.startswith('<'):
            out.append(tag(part))
        else:
            out.append(tr(part))
    html = ''.join(out)

    url = f'{BASE}/{lang}/'
    html = html.replace('<html lang="en">', f'<html lang="{lang}">', 1)
    html = re.sub(r'<link rel="canonical" href="[^"]*">', f'<link rel="canonical" href="{url}">', html, 1)
    html = re.sub(r'<meta property="og:url" content="[^"]*">', f'<meta property="og:url" content="{url}">', html, 1)
    html = re.sub(r'<meta property="og:locale" content="[^"]*">', f'<meta property="og:locale" content="{locale}">', html, 1)
    html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Built from index.html by i18n/build.py. Do not edit this file: edit index.html or i18n/*.json and run the script. -->', 1)

    unused_js = [k for k in js if not any(q + k + q in src for q in "'\"`")]
    (ROOT / lang).mkdir(exist_ok=True)
    (ROOT / lang / 'index.html').write_text(html, encoding='utf-8')
    return sorted(set(missing), key=missing.index), unused_js


def main():
    src = (ROOT / 'index.html').read_text(encoding='utf-8')
    ok = True
    for lang, locale in LANGS.items():
        missing, unused_js = build(lang, locale, src)
        print(f'{lang}/index.html built', '' if not missing else f'- {len(missing)} texts still in English:')
        for m in missing:
            print('   ', json.dumps(m, ensure_ascii=False))
        for k in unused_js:
            print(f'    script text not found in index.html: {k!r}')
        ok = ok and not missing and not unused_js
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
